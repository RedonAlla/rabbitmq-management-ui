import { PencilIcon } from "lucide-react"
import { Badge } from "@/components/reui/badge"
import { PageHeader } from "@/components/page-header"
import { RegionError } from "@/components/region-states"
import { FactPanel } from "@/components/detail"
import { Button } from "@/components/ui/button"
import { useDialogs } from "@/components/dialogs/dialogs-provider"
import { useCluster } from "@/store/cluster"
import { fmtAgo, fmtDate } from "@/lib/format"
import NodesTable from "./cluster/NodesTable"
import ListenersTable from "./cluster/ListenersTable"

export function ClusterView() {
  const { data, status, error, actions } = useCluster()
  const { openDialog } = useDialogs()

  return (
    <div className="flex min-w-0 flex-col gap-6">
      <PageHeader
        title="Cluster"
        actions={
          <Button
            type="button"
            onClick={() => openDialog({ type: "edit-cluster-name" })}
          >
            <PencilIcon data-icon="inline-start" aria-hidden="true" />
            Change name
          </Button>
        }
        eyebrow={
          <>
            <Badge variant="success-light">Online</Badge>
            <span className="text-xs text-muted-foreground">
              RabbitMQ {data.cluster.version} · Erlang {data.cluster.erlang}
            </span>
          </>
        }
        description={
          <>
            <p>
              The cluster name can be used by clients to identify clusters over
              AMQP connections, and is used by the shovel and federation plugins
              to identify which clusters a message has been routed through.
            </p>
            <p>
              Note that the cluster name is announced to clients in the AMQP
              server properties; i.e. before authentication has taken
              place. Therefore it should not be considered secret.
            </p>
            <p>
              The cluster name is generated by default from the name of the first
              node in the cluster, but can be changed.
            </p>
          </>
        }
      />

      {error ? <RegionError message={error} onRetry={actions.retry} /> : null}

      <div className="grid min-w-0 gap-3  xl:grid-cols-[minmax(0,22rem)_minmax(0,1fr)] xl:items-start">
        <FactPanel
          title="Cluster identity"
          description="Reported by the management API."
          facts={[
            { label: "Cluster", value: data.cluster.name, mono: true },
            { label: "Version", value: data.cluster.version },
            { label: "Erlang", value: data.cluster.erlang },
            { label: "First node", value: data.cluster.node, mono: true },
            {
              label: "Started",
              value: `${fmtDate(data.cluster.startedAt)} · ${fmtAgo(data.cluster.startedAt, new Date().getTime())}`,
            },
            { label: "Members", value: `${data.nodes.length} nodes` },
            { label: "Listeners", value: `${data.ports.length} ports` },
          ]}
        />

        <ListenersTable
          ports={data.ports}
          loading={status === "loading"}
          error={error}
          onRetry={actions.retry}
        />
      </div>

      <NodesTable
        nodes={data.nodes}
        loading={status === "loading"}
        error={error}
        onRetry={actions.retry}
      />
    </div>
  )
}
